  }

  signingConfigs {
    create("release") {
      val keystorePath = System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks"
      storeFile = file(keystorePath)
      storePassword = System.getenv("STORE_PASSWORD")
      keyAlias = "upload"
      keyPassword = System.getenv("KEY_PASSWORD")
    }
    create("debugConfig") {
      val debugKeystore = file("${rootDir}/debug.keystore")
      val debugKeystoreBase64 = file("${rootDir}/debug.keystore.base64")

      if (!debugKeystore.exists() && debugKeystoreBase64.exists()) {
        try {
          val base64Content = debugKeystoreBase64.readText().trim()
          val decodedBytes = Base64.getDecoder().decode(base64Content)
          debugKeystore.writeBytes(decodedBytes)
        } catch (e: Exception) {
          logger.warn("Failed to decode debug.keystore.base64: ${e.message}")
        }
      }

      storeFile = debugKeystore
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      signingConfig = signingConfigs.getByName("release")
    }
    debug {
      val debugKeystoreExists = file("${rootDir}/debug.keystore").exists() || 
                                file("${rootDir}/debug.keystore.base64").exists()
      if (debugKeystoreExists) {
        signingConfig = signingConfigs.getByName("debugConfig")
      }
    }
